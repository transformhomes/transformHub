// Bridge for the built-in pages (Home, Explorer, Tasks, Calendar) only.
// Web sections (Outlook, Teams, Claude...) never get this.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('cc', {
  getData: () => ipcRenderer.invoke('data:get'),
  setData: (patch) => ipcRenderer.invoke('data:set', patch),
  onChanged: (fn) => ipcRenderer.on('data:changed', (_e, d) => fn(d)),
  getSettings: () => ipcRenderer.invoke('app:settings'),
  getFeeds: () => ipcRenderer.invoke('feeds:get'),
  refreshFeeds: () => ipcRenderer.invoke('feeds:refresh'),
  onFeedsChanged: (fn) => ipcRenderer.on('feeds:changed', (_e, s) => fn(s)),
  getProjects: () => ipcRenderer.invoke('projects:list'),
  getRoots: () => ipcRenderer.invoke('explorer:roots'),
  getSettingsPage: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (p) => ipcRenderer.invoke('settings:save', p),
  saveSettingsRaw: (t) => ipcRenderer.invoke('settings:save-raw', t),
  pickFolder: () => ipcRenderer.invoke('settings:pick-folder'),
  restartApp: () => ipcRenderer.send('app:restart'),
  openConfig: () => ipcRenderer.invoke('settings:open-file'),
  getRecent: (force) => ipcRenderer.invoke('recent:list', !!force),
  openRecent: (id, reveal) => ipcRenderer.invoke('recent:open', id, !!reveal),
  setHomeRecent: (on) => ipcRenderer.invoke('settings:home-recent', !!on),
  getHomeRecent: () => ipcRenderer.invoke('settings:home-recent-get'),
  getHomeBackground: () => ipcRenderer.invoke('home:background'),
  onHomeBackground: (fn) => ipcRenderer.on('home:bg', () => fn()),
  pickBackground: () => ipcRenderer.invoke('settings:bg-pick'),
  setBackgroundDim: (n) => ipcRenderer.invoke('settings:bg-dim', n),
  removeBackground: () => ipcRenderer.invoke('settings:bg-remove'),
  getLock: () => ipcRenderer.invoke('lock:get'),
  saveLock: (p) => ipcRenderer.invoke('lock:save', p),
  removeLock: (pin) => ipcRenderer.invoke('lock:remove', pin),
  lockNow: () => ipcRenderer.invoke('lock:now'),
  listBackups: () => ipcRenderer.invoke('settings:backups'),
  restoreBackup: (name) => ipcRenderer.invoke('settings:restore-backup', name),
  reorderApps: (ids) => ipcRenderer.invoke('app:reorder', ids),
  setAppGroup: (id, group) => ipcRenderer.invoke('app:set-group', id, group),
  appIcons: () => ipcRenderer.invoke('app:icons'),
  addApp: () => ipcRenderer.invoke('app:add'),
  removeApp: (id) => ipcRenderer.invoke('app:remove', id),
  launchApp: (id) => ipcRenderer.invoke('app:launch', id),
  snapApp: (id) => ipcRenderer.invoke('app:snap', id),
  restoreLayout: () => ipcRenderer.invoke('app:restore-layout'),
  layoutState: () => ipcRenderer.invoke('app:layout-state'),
  openWith: (id, root, rel) => ipcRenderer.invoke('app:open-with', id, root, rel),
  toggleFav: (root, rel, name) => ipcRenderer.invoke('explorer:fav', root, rel, name),
  openFolder: (id) => ipcRenderer.invoke('projects:open-folder', id),
  openArcane: () => ipcRenderer.invoke('projects:open-arcane'),
  go: (sectionId) => ipcRenderer.send('cc:select', sectionId),
  transferFile: (srcRoot, srcRel, dstRoot, dstRel, copy) => ipcRenderer.invoke('fs:transfer', srcRoot, srcRel, dstRoot, dstRel, copy === true),
  importFiles: (dstRoot, dstRel, paths) => ipcRenderer.invoke('fs:import', dstRoot, dstRel, paths),
  openInWeb: (root, rel) => ipcRenderer.invoke('fs:open-web', root, rel),
  dragOut: (root, rel) => ipcRenderer.send('fs:drag-out', root, rel),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file) || ''; } catch { return ''; } },
  listDir: (project, rel) => ipcRenderer.invoke('fs:list', project, rel),
  readFile: (project, rel) => ipcRenderer.invoke('fs:read', project, rel),
  openFile: (project, rel) => ipcRenderer.invoke('fs:open', project, rel),
  revealFile: (project, rel) => ipcRenderer.invoke('fs:reveal', project, rel),
  getOutlook: (force) => ipcRenderer.invoke('outlook:get', force === true),
  openPowerShell: (id, rel) => ipcRenderer.invoke('fs:powershell', id, rel),
  copyPath: (id, rel) => ipcRenderer.invoke('fs:copy-path', id, rel),
  getProperties: (id, rel) => ipcRenderer.invoke('fs:properties', id, rel),
  getTodo: () => ipcRenderer.invoke('todo:get'),
  completeTodo: (title) => ipcRenderer.invoke('todo:complete', title),
  refreshTodo: () => ipcRenderer.invoke('todo:refresh'),
  onTodo: (fn) => ipcRenderer.on('todo:changed', (_e, s) => fn(s)),
  navigate: (params) => ipcRenderer.send('cc:navigate', params),
  onNavigate: (fn) => ipcRenderer.on('nav:params', (_e, p) => fn(p)),
});
